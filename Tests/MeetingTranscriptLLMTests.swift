import Foundation

// The meeting transcript LLM pass (fork): it finds each utterance in both
// saved body forms, rewrites only utterance text (never timestamps, speakers,
// frontmatter or other sections), skips an utterance that changed while the
// model ran, backs the transcript up before the one rewrite, and resumes a
// paused job from its checkpoint instead of starting over or losing it.

private let styledTranscript = """
---
title: "Meeting with Sarah"
capture_id: "5E9A-TEST"
capture_type: meeting
format_version: 1
transcript_style: styled
---

# Meeting with Sarah

Recorded Apr 7, 2026 at 9:14 AM  •  12 min, 30 sec  •  42 words  •  3 turns

## Transcript

**00:00**  [Mic/You]
давай посмотрим логи в графане сегодня

**00:04**  [System/[[Sarah]]]
да

**01:02:03**  [System/Speaker 2]
надо задеплоить фронтенд на стейдж
и проверить ручку

## Notes

kept as is
"""

private let rawTranscript = """
---
capture_id: "RAW-1"
transcript_style: raw
---

# Meeting Recording - Apr 7, 2026 at 9:14 AM

## Full Transcript

[00:00] [Mic/You] проверь тесты в плейрайте пожалуйста

[00:04] [System/Sarah] ок

---

*Generated by Transcripted with Parakeet + PyAnnote (local) | Duration: 12:30 | 42 words | 2 speakers*
"""

@MainActor
private final class FakeMeetingRefiner: MeetingUtteranceRefiner {
    var answers: [String: MeetingUtteranceRefinement] = [:]
    var seen: [String] = []
    var meetingRefinerModelID: String { "fake-model" }

    func refineMeetingUtterance(_ text: String) async -> MeetingUtteranceRefinement {
        seen.append(text)
        return answers[text] ?? .refined(text.uppercased())
    }
}

private func tempDirectory(_ label: String) -> URL {
    let url = FileManager.default.temporaryDirectory
        .appendingPathComponent("MeetingTranscriptLLMTests-\(label)-\(UUID().uuidString)", isDirectory: true)
    try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
    return url
}

/// Waits (bounded by attempts, not wall-clock asserts) until the job file is gone.
private func waitForJobs(in store: MeetingTranscriptLLMJobStore, attempts: Int = 400) async {
    for _ in 0..<attempts where !store.all().isEmpty {
        try? await Task.sleep(nanoseconds: 10_000_000)
    }
}

@MainActor
func testMeetingTranscriptLLM() async {
    runSuite("MeetingTranscriptLLMDocument finds utterances in both body forms") {
        let styled = MeetingTranscriptLLMDocument.utterances(in: styledTranscript)
        assertEqual(styled.map(\.text), [
            "давай посмотрим логи в графане сегодня",
            "да",
            "надо задеплоить фронтенд на стейдж\nи проверить ручку",
        ], "styled entries, including a legacy wiki-linked label and a multi-line utterance")
        assertEqual(styled.map(\.index), [0, 1, 2], "utterances are numbered in order")
        assertTrue(styled.allSatisfy { $0.inlinePrefix == nil }, "styled text sits under its header")

        let raw = MeetingTranscriptLLMDocument.utterances(in: rawTranscript)
        assertEqual(raw.map(\.text), ["проверь тесты в плейрайте пожалуйста", "ок"], "raw inline entries")
        assertEqual(raw.first?.inlinePrefix, "[00:00] [Mic/You] ", "the timestamp and label stay as the prefix")
        assertEqual(MeetingTranscriptLLMDocument.captureID(in: styledTranscript), "5E9A-TEST", "capture id read from frontmatter")
        assertEqual(MeetingTranscriptLLMDocument.utterances(in: "# No transcript here").count, 0, "no transcript section, no utterances")
    }

    runSuite("MeetingTranscriptLLMDocument rewrites only utterance text and marks the file") {
        let utterances = MeetingTranscriptLLMDocument.utterances(in: styledTranscript)
        let originals = Dictionary(uniqueKeysWithValues: utterances.map { ($0.index, $0.text) })
        let rewrite = MeetingTranscriptLLMDocument.applying(
            [0: "Давай посмотрим логи в Grafana сегодня.", 2: "Надо задеплоить frontend на stage\nи проверить ручку."],
            originals: originals,
            to: styledTranscript,
            marker: "gemma-test"
        )
        assertEqual(rewrite.applied, 2, "both replacements land")
        assertTrue(rewrite.markdown.contains("**00:00**  [Mic/You]\nДавай посмотрим логи в Grafana сегодня."), "header kept, text replaced")
        assertTrue(rewrite.markdown.contains("**01:02:03**  [System/Speaker 2]\nНадо задеплоить frontend на stage и проверить ручку."), "a multi-line utterance becomes one paragraph")
        assertTrue(rewrite.markdown.contains("**00:04**  [System/[[Sarah]]]\nда\n"), "an utterance with no replacement is untouched")
        assertTrue(rewrite.markdown.contains("## Notes\n\nkept as is"), "other sections are untouched")
        assertTrue(rewrite.markdown.contains("transcript_llm: \"gemma-test\"\n---"), "the marker closes the frontmatter")
        assertTrue(MeetingTranscriptLLMDocument.isProcessed(rewrite.markdown), "a marked transcript reads as processed")
        assertFalse(MeetingTranscriptLLMDocument.isProcessed(styledTranscript), "an unmarked one doesn't")

        let raw = MeetingTranscriptLLMDocument.applying(
            [0: "Проверь тесты в Playwright, пожалуйста."],
            originals: [0: "проверь тесты в плейрайте пожалуйста"],
            to: rawTranscript,
            marker: "gemma-test"
        )
        assertTrue(raw.markdown.contains("[00:00] [Mic/You] Проверь тесты в Playwright, пожалуйста.\n"), "raw prefix kept")
        assertTrue(raw.markdown.contains("*Generated by Transcripted"), "the raw footer is untouched")
    }

    runSuite("MeetingTranscriptLLMDocument never overwrites an utterance that changed meanwhile") {
        let rewrite = MeetingTranscriptLLMDocument.applying(
            [0: "MODEL TEXT"],
            originals: [0: "what the model saw, no longer in the file"],
            to: styledTranscript,
            marker: "gemma-test"
        )
        assertEqual(rewrite.applied, 0, "a stale replacement is skipped")
        assertTrue(rewrite.markdown.contains("давай посмотрим логи в графане сегодня"), "the current text stays")
    }

    await runSuite("MeetingTranscriptLLMWorker rewrites a queued transcript once, after a backup") {
        let root = tempDirectory("worker")
        defer { try? FileManager.default.removeItem(at: root) }
        let store = MeetingTranscriptLLMJobStore(directory: root.appendingPathComponent("state", isDirectory: true))
        let transcript = root.appendingPathComponent("2026-04-07 Meeting with Sarah.md")
        try? styledTranscript.write(to: transcript, atomically: true, encoding: .utf8)

        let refiner = FakeMeetingRefiner()
        let worker = MeetingTranscriptLLMWorker()
        await worker.configure(refiner: refiner, store: store, onTranscriptChanged: { _ in }, log: { _ in })
        await worker.enqueue(transcriptURL: transcript)
        await waitForJobs(in: store)

        let result = (try? String(contentsOf: transcript, encoding: .utf8)) ?? ""
        assertTrue(result.contains("ДАВАЙ ПОСМОТРИМ ЛОГИ В ГРАФАНЕ СЕГОДНЯ"), "a long utterance went through the model")
        assertTrue(result.contains("[System/[[Sarah]]]\nда\n"), "a two-word utterance keeps its text without a model call")
        assertFalse(refiner.seen.contains("да"), "short utterances never reach the model")
        assertTrue(MeetingTranscriptLLMDocument.isProcessed(result), "the rewritten transcript is marked")
        let backups = (try? FileManager.default.contentsOfDirectory(atPath: store.originalsDirectory.path)) ?? []
        assertEqual(backups.count, 1, "the transcript as it was is backed up first")
        if let backup = backups.first {
            let saved = (try? String(contentsOf: store.originalsDirectory.appendingPathComponent(backup), encoding: .utf8)) ?? ""
            assertEqual(saved, styledTranscript, "the backup is the transcript byte for byte")
        }
        assertTrue(store.all().isEmpty, "the job is gone once the transcript is rewritten")

        await worker.enqueue(transcriptURL: transcript)
        assertTrue(store.all().isEmpty, "a marked transcript is never queued again")
    }

    await runSuite("MeetingTranscriptLLMWorker pauses on an unready model and resumes from its checkpoint") {
        let root = tempDirectory("pause")
        defer { try? FileManager.default.removeItem(at: root) }
        let store = MeetingTranscriptLLMJobStore(directory: root.appendingPathComponent("state", isDirectory: true))
        let transcript = root.appendingPathComponent("raw.md")
        try? rawTranscript.write(to: transcript, atomically: true, encoding: .utf8)

        let refiner = FakeMeetingRefiner()
        refiner.answers["проверь тесты в плейрайте пожалуйста"] = .unavailable
        let worker = MeetingTranscriptLLMWorker()
        await worker.configure(refiner: refiner, store: store, onTranscriptChanged: { _ in }, log: { _ in })
        await worker.enqueue(transcriptURL: transcript)
        for _ in 0..<200 where refiner.seen.isEmpty {
            try? await Task.sleep(nanoseconds: 10_000_000)
        }
        assertEqual(store.all().count, 1, "an unready model leaves the job queued on disk")
        assertEqual(
            (try? String(contentsOf: transcript, encoding: .utf8)) ?? "",
            rawTranscript,
            "and the transcript untouched"
        )

        // A new run (a relaunch) with a ready model picks the same job up.
        let ready = FakeMeetingRefiner()
        let relaunched = MeetingTranscriptLLMWorker()
        await relaunched.configure(refiner: ready, store: store, onTranscriptChanged: { _ in }, log: { _ in })
        await waitForJobs(in: store)
        let result = (try? String(contentsOf: transcript, encoding: .utf8)) ?? ""
        assertTrue(result.contains("[00:00] [Mic/You] ПРОВЕРЬ ТЕСТЫ В ПЛЕЙРАЙТЕ ПОЖАЛУЙСТА"), "the resumed job finished the transcript")
        assertTrue(store.all().isEmpty, "and cleared its job")
    }

    await runSuite("MeetingTranscriptLLMWorker drops the job of a deleted transcript and keeps rejected text") {
        let root = tempDirectory("gone")
        defer { try? FileManager.default.removeItem(at: root) }
        let store = MeetingTranscriptLLMJobStore(directory: root.appendingPathComponent("state", isDirectory: true))
        try? store.save(MeetingTranscriptLLMJob(
            captureID: "GONE", transcriptPath: root.appendingPathComponent("missing.md").path, enqueuedAt: Date()
        ))
        let transcript = root.appendingPathComponent("kept.md")
        try? rawTranscript.write(to: transcript, atomically: true, encoding: .utf8)
        let refiner = FakeMeetingRefiner()
        refiner.answers["проверь тесты в плейрайте пожалуйста"] = .keep
        let worker = MeetingTranscriptLLMWorker()
        await worker.configure(refiner: refiner, store: store, onTranscriptChanged: { _ in }, log: { _ in })
        await worker.enqueue(transcriptURL: transcript)
        await waitForJobs(in: store)
        assertTrue(store.all().isEmpty, "a job whose transcript is gone is dropped, not retried forever")
        let result = (try? String(contentsOf: transcript, encoding: .utf8)) ?? ""
        assertTrue(result.contains("[00:00] [Mic/You] проверь тесты в плейрайте пожалуйста"), "a kept answer leaves the text as recognized")
    }
}
